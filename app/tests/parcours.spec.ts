test("éditeur : rubriques par famille, brouillon, export, import, modification", async ({ page }) => {
  const app = await commencer(page)
  await page.goto('/#editeur')
  await page.locator('#e-fam').selectOption('chant')
  await page.locator('#e-title').fill('Bella Ciao')
  await page.locator('#e-auteur').fill('Chant populaire italien')
  await page.getByRole('button', { name: 'Enregistrer la carte' }).click()
  await expect(page.getByText('Il manque : Son histoire.')).toBeVisible()
  await page.locator('#e-fait').fill('Chant des partisans italiens, repris dans le monde entier.')
  await expect(page.locator('.apercu .carte h3')).toHaveText('Bella Ciao')
  await page.getByRole('button', { name: 'Enregistrer la carte' }).click()
  await expect(page.getByText('Carte ajoutée')).toBeVisible()

  await page.locator('#e-title').fill('Brouillon en cours')
  await page.waitForTimeout(300)
  await page.reload()
  await page.goto('/#editeur')
  await expect(page.locator('#e-title')).toHaveValue('Brouillon en cours')
  await page.getByRole('button', { name: 'Nouvelle carte' }).click()

  await page.locator('#pack-nom').fill('Chants')
  await page.getByRole('button', { name: 'Générer le pack' }).click()
  const pack = await page.locator('#pack-texte').inputValue()
  await page.locator('#import-texte').fill(pack)
  await page.getByRole('button', { name: 'Importer le texte' }).click()
  await expect(page.getByText('importée(s), non signées')).toBeVisible()
  await page.locator('#import-texte').fill('pas un pack')
  await page.getByRole('button', { name: 'Importer le texte' }).click()
  await expect(page.getByText("n'est pas un pack valide")).toBeVisible()

  await page.goto('/#album')
  await page.getByRole('button', { name: 'Bella Ciao' }).first().click()
  await page.getByRole('button', { name: 'Modifier' }).click()
  await expect(page.locator('#e-title')).toHaveValue('Bella Ciao')
  await app.verifierPropre()
})

